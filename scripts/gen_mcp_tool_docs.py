"""Generate docs/mcp_tools.rst from the live MCP tool schemas.

The argument tables are built from the input schemas the server publishes,
so the reference cannot drift from the code. Re-run after changing a tool:

    python scripts/gen_mcp_tool_docs.py [dataset_root] [output.rst]
"""

from __future__ import annotations

import inspect
import json
import sys
from pathlib import Path

import anyio
from mcp import Client

from eda_schema.mcp.context import DatasetContext
from eda_schema.mcp.server import build_server

HEADER = """.. This file is generated by scripts/gen_mcp_tool_docs.py. Do not edit by hand.

MCP Tool Reference
==================

Every tool is read-only and returns the response envelope described in
:doc:`mcp`. Arguments marked *required* have no default. Values shown as
``null`` mean "not set". Sizes and limits are clamped by the server
(``--max-rows`` and ``--max-response-chars``).

"""


def type_name(prop: dict) -> str:
    """Human-readable type of one JSON-schema property."""
    if "$ref" in prop:
        return 'range object ``{"min": ..., "max": ...}``'
    if "anyOf" in prop:
        return " or ".join(type_name(p) for p in prop["anyOf"] if p.get("type") != "null")
    kind = prop.get("type", "")
    if kind == "array":
        items = prop.get("items", {})
        if "enum" in items:
            return "list of: " + ", ".join(f"``{e}``" for e in items["enum"])
        return f"list of {type_name(items)}"
    if "enum" in prop:
        return "one of: " + ", ".join(f"``{e}``" for e in prop["enum"])
    return kind


def tool_section(tool) -> list[str]:
    """RST lines for one tool."""
    title = f"``{tool.name}``"
    lines = [title, "-" * len(title), "", inspect.cleandoc(tool.description or ""), ""]
    props = tool.input_schema.get("properties", {})
    required = set(tool.input_schema.get("required", []))
    if not props:
        return [*lines, "*No arguments.*", ""]
    lines += [
        ".. list-table::",
        "   :header-rows: 1",
        "   :widths: 18 30 14 38",
        "",
        "   * - Argument",
        "     - Type",
        "     - Default",
        "     - Description",
    ]
    for name, prop in props.items():
        bounds = [
            f"{label}{prop[key]}"
            for key, label in (
                ("minimum", ">= "),
                ("maximum", "<= "),
                ("minItems", "at least "),
                ("maxItems", "at most "),
            )
            if key in prop
        ]
        default = "*required*" if name in required else f"``{json.dumps(prop.get('default'))}``"
        desc = prop.get("description", "") + (f" ({', '.join(bounds)})" if bounds else "")
        lines += [f"   * - ``{name}``", f"     - {type_name(prop)}", f"     - {default}", f"     - {desc}"]
    return [*lines, ""]


async def render(dataset: str) -> str:
    server = build_server(DatasetContext(dataset))
    async with Client(server) as client:
        tools = (await client.list_tools()).tools
    body = [line for tool in tools for line in tool_section(tool)]
    return HEADER + "\n".join(body)


def main() -> None:
    dataset = sys.argv[1] if len(sys.argv) > 1 else "dataset/test"
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("docs/mcp_tools.rst")
    output.write_text(anyio.run(render, dataset), encoding="utf-8")
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
